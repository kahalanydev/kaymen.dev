/* --- the case-study comparison ------------------------------------------------
   A mid-market US agency, which is the band this work actually sits in.
   Researched Aug 2026 against the FullStack Labs price guide: US agency tiers
   run small-class $90–160/hr, mid-market $120–250, big-business $250–350.

   HOURS_PER_DAY is a RANGE on purpose. A day that carried a commit is not a
   timesheet, and nobody knows whether an agency bills six hours or eight for
   the same work. Publishing a range says that out loud; publishing a single
   figure would be pretending to a precision we do not have, on the one part of
   the page that is a claim about somebody else's money. */
